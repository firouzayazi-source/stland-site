/** یک بار برای هر نسخه‌ی محتوا — بعد از ثبتِ همه‌چیز (init دیر)، نه در درخواستِ ناشناسِ عادی که کش است */
add_action( 'init', static function (): void {
	$done = (array) get_option( 'stlh_store_content', [] );
	if ( ( $done['ver'] ?? '' ) === STLH_CONTENT_VER || wp_doing_ajax() ) {
		return;
	}
	if ( get_transient( 'stlh_store_content_lock' ) ) {
		return;
	}
	set_transient( 'stlh_store_content_lock', 1, 5 * MINUTE_IN_SECONDS );
	stlh_store_content_apply();
	delete_transient( 'stlh_store_content_lock' );
}, 99 );

/** برگشت: متنِ قبلیِ صفحه‌ها و المنتورشان (برای وقتی چیزی عجیب شد) */
function stlh_store_content_revert(): int {
	$n = 0;
	foreach ( stlh_store_pages() as [ $id ] ) {
		$bak = get_post_meta( $id, 'stlh_bak_content', true );
		if ( '' === (string) $bak ) {
			continue;
		}
		wp_update_post( [ 'ID' => $id, 'post_content' => $bak ] );
		if ( $mode = (string) get_post_meta( $id, 'stlh_bak_elementor_mode', true ) ) {
			update_post_meta( $id, '_elementor_edit_mode', $mode );
		}
		update_post_meta( $id, '_wp_page_template', (string) get_post_meta( $id, 'stlh_bak_template', true ) ?: 'default' );
		$n++;
	}
	return $n;
}

