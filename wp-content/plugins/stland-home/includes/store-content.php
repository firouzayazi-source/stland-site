	update_option( 'stlh_store_content', $log, false );
	if ( function_exists( 'stlh_cache_flush' ) ) {
		stlh_cache_flush();
	}
	if ( function_exists( 'stlh_pc_purge' ) ) {
		stlh_pc_purge();
	}
	return $log;
