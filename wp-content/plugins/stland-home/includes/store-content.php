	] ) );
	$set( 'faq', implode( "\n\n", array_map( static fn( $qa ) => $qa[0] . "\n" . wp_strip_all_tags( $qa[1] ), [
		[ 'شرایط خرید اقساطی گوشی‌های استوک لند به چه صورت است؟', 'اقساط از ۱ ماه تا ۱۲ ماه با ضمانت طلا یا چک معتبر؛ خرید با اسنپ‌پی هم ممکن است. برای پیش‌پرداخت و مبلغ اقساط با ۰۹۱۲ ۷۴۸ ۸۴۳۴ تماس بگیرید یا در اینستاگرام @stock_land.ir پیام بدهید.' ],
		[ 'آیا گوشی‌های کارکرده مهلت تست و تعویض دارند؟', 'بله؛ دست‌کم یک هفته مهلت تست برای همه‌ی ایرادهای فنی (جز مواردی که هنگام خرید در فروشگاه تست و تأیید شده) و تا یک هفته امکان تعویضِ کالای سالم.' ],
		[ 'گوشی قدیمی‌ام را معاوضه می‌کنید؟', 'بله، همه‌ی گوشی‌های قدیمی را برای معاوضه با گوشی جدید کارشناسی می‌کنیم. عکس و مشخصاتش را در اینستاگرام @stock_land.ir بفرستید یا به فروشگاه بیایید.' ],
		[ 'آیا امکان خرید حضوری و مراجعه به فروشگاه وجود دارد؟', 'بله. ' . $f['address'] . '. ساعت کاری: ' . $f['hours'] . '.' ],
		[ 'به شهرهای دیگر هم ارسال دارید؟', 'بله، به همه‌ی شهرهای ایران با پست، تیپاکس و پیک.' ],
		[ 'چگونه از سلامت سخت‌افزاری دستگاه مطمئن شویم؟', 'هر گوشی کارکرده پیش از فروش کامل تست می‌شود و «دفترچه‌ی سلامت»ش — سلامت باتری، چرخه‌ی شارژ، ریجستری، پارت‌نامبر و تست قطعه‌به‌قطعه — در صفحه‌ی همان محصول منتشر می‌شود. عکس‌ها عکس واقعی همان دستگاه است.' ],
