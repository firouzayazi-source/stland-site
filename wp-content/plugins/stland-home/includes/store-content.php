function stlh_store_content_apply(): array {
	$log  = [ 'at' => gmdate( 'c' ), 'ver' => STLH_CONTENT_VER, 'pages' => [], 'drafts' => [], 'noindex' => [], 'settings' => [] ];
	$prev = (array) get_option( 'stlh_store_content', [] );

	foreach ( stlh_store_pages() as $slug => [ $id, $title, $desc, $html ] ) {
		$post = get_post( $id );
		if ( ! $post || 'page' !== $post->post_type || rawurldecode( $post->post_name ) !== $slug ) {
			$log['pages'][ $slug ] = 'skip: not found';
			continue;
		}
		// اگر بعد از اجرای قبلیِ ما کسی دستی ویرایشش کرده، دست نزن
		if ( ! empty( $prev['stamp'][ $id ] ) && $post->post_modified_gmt !== $prev['stamp'][ $id ] ) {
			$log['pages'][ $slug ] = 'skip: edited by hand';
			continue;
		}
		if ( '' === (string) get_post_meta( $id, 'stlh_bak_content', true ) ) {
			add_post_meta( $id, 'stlh_bak_content', $post->post_content, true );
			add_post_meta( $id, 'stlh_bak_elementor_mode', (string) get_post_meta( $id, '_elementor_edit_mode', true ), true );
			add_post_meta( $id, 'stlh_bak_template', (string) get_post_meta( $id, '_wp_page_template', true ), true );
		}
		wp_update_post( [ 'ID' => $id, 'post_title' => $title, 'post_content' => $html, 'post_status' => 'publish' ] );
		delete_post_meta( $id, '_elementor_edit_mode' ); // المنتور دیگر این صفحه را نمی‌سازد؛ _elementor_data برای برگشت می‌ماند
		update_post_meta( $id, '_wp_page_template', 'default' );
		update_post_meta( $id, '_yoast_wpseo_metadesc', $desc );
		update_post_meta( $id, '_yoast_wpseo_title', $title . ' | استوک لند' );
		clean_post_cache( $id );
		$log['stamp'][ $id ]   = get_post( $id )->post_modified_gmt;
		$log['pages'][ $slug ] = 'ok';
	}

	foreach ( stlh_store_drafts() as $id => $slug ) {
		$post = get_post( $id );
		if ( $post && 'page' === $post->post_type && rawurldecode( $post->post_name ) === $slug && 'publish' === $post->post_status ) {
			wp_update_post( [ 'ID' => $id, 'post_status' => 'draft' ] );
			$log['drafts'][] = $slug;
		}
	}

	/*
	 * ۳: صاحب فروشگاه (مهر ۱۴۰۵): «صفحه‌هایی که غیرفعال کردی را کلاً پاک کن؛ هیچ اسمی از باکالا
	 * یا سایتِ دیگری نماند.» پیش‌نویس‌های بالا برای همیشه حذف می‌شوند (فقط اگر هنوز پیش‌نویس‌اند
	 * و نامکشان همان است)، و سه قالبِ نمونه‌ی المنتور که متنِ «باکالا» داشتند.
	 */
	foreach ( stlh_store_drafts() as $id => $slug ) {
		$post = get_post( $id );
		if ( $post && 'page' === $post->post_type && 'draft' === $post->post_status && in_array( rawurldecode( $post->post_name ), [ $slug, $slug . '__trashed' ], true ) ) {
			wp_delete_post( $id, true );
			$log['deleted'][] = $slug;
		}
	}
	foreach ( [ 44204, 43741, 43714 ] as $id ) {
		$post = get_post( $id );
		if ( ! $post || 'elementor_library' !== $post->post_type ) {
			continue;
		}
		$text = $post->post_content . (string) get_post_meta( $id, '_elementor_data', true );
		if ( str_contains( $text, 'باکالا' ) || str_contains( $text, '\u0628\u0627\u06a9\u0627\u0644\u0627' ) ) {
			wp_delete_post( $id, true );
			$log['deleted'][] = 'elementor_library:' . $id;
		}
	}

	foreach ( stlh_store_noindex_slugs() as $slug ) {
		$page = get_page_by_path( $slug );
		if ( $page ) {
			update_post_meta( $page->ID, '_yoast_wpseo_meta-robots-noindex', '1' );
			$log['noindex'][] = $slug;
		}
	}

	// تنظیماتِ افزونه — فقط کلیدهایی که هنوز مقدارِ قدیمی/پیش‌فرض دارند
	$f    = stlh_store_facts();
	$opts = (array) get_option( STLH_OPT, [] );
	$set  = static function ( string $k, $v, array $old_values = [] ) use ( &$opts, &$log ): void {
		$cur  = $opts[ $k ] ?? null;
