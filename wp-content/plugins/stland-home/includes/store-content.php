		$stale = 'faq' === $k && is_string( $cur ) && str_contains( $cur, '۰۹۰۵۰۳۲۳۲۱۷' );
		if ( null === $cur || '' === $cur || $stale || in_array( $norm( $cur ), $olds, true ) ) {
			$opts[ $k ]           = $v;
			$log['settings'][]    = $k;
		}
	};
	$set( 'phone', $f['phone'], [ '09050323217' ] );
	$set( 'opening_hours', $f['hours_spec'], [ "شنبه تا پنج‌شنبه|10:00|23:00\nجمعه|16:00|23:00" ] );
	$set( 'payment_methods', $f['payment'] );
	$set( 'map_url', $f['map'] );
	$set( 'telegram', $f['telegram'] );
	$set( 'store_email', $f['email'] );
	$set( 'store_facts', implode( "\n", [
		'خرید اقساطی آیفون از ۱ تا ۱۲ ماه با ضمانت طلا یا چک معتبر؛ اسنپ‌پی هم پذیرفته می‌شود.',
		'هر آیفون کارکرده دست‌کم یک هفته مهلت تست دارد (همه‌ی ایرادهای فنی، جز مواردی که هنگام خرید در فروشگاه تست و تأیید شده).',
		'تا یک هفته امکان تعویض کالای سالم؛ بازگرداندن وجه در صورت ایراد فنی.',
		'معاوضه‌ی همه‌ی گوشی‌های قدیمی با گوشی جدید.',
		'ارسال به همه‌ی شهرهای ایران با پست، تیپاکس و پیک؛ خرید حضوری در قم.',
		'لوازم جانبی: اصل اپل و برندهای معتبر دیگر، با گارانتی.',
